// components can import getDictionary/Locale/Dictionary from here directly without pulling
// in the database layer into the browser bundle. src/lib/i18n.ts re-exports all of this
// for server-side call sites and additionally provides the DB-backed getLocale().

export type Locale = "en" | "cs";
export const DEFAULT_LOCALE: Locale = "en";

export function czCount(n: number, one: string, few: string, many: string) {
  if (n === 1) return one;
  if (n >= 2 && n <= 4) return few;
  return many;
}

