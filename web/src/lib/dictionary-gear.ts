// dictionary.ts plugs these in as `gear`. Same rule: no imports beyond plain
// helpers, so Client Components can use it.

function cz(n: number, one: string, few: string, many: string) {
  if (n === 1) return one;
  if (n >= 2 && n <= 4) return few;
  return many;
}

